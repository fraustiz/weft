// What the pasteboard's types say about its content, before anything is
// read: reading the types costs no privacy prompt, reading the text may.
//
// The markers come from nspasteboard.org, which password managers and
// clipboard tools follow (docs/PLAN.md §3).

public enum PasteboardPolicy {
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    /// Names the app that wrote the content.
    public static let source = "org.nspasteboard.source"
    public static let plainText = "public.utf8-plain-text"

    /// Content other apps asked clipboard tools to leave alone.
    public static let excludedTypes: Set<String> = [concealed, transient, autoGenerated]

    public enum Decision: Sendable, Equatable {
        /// Plain text that may be read and shared.
        case readText
        /// Marked concealed, transient or auto-generated: not read at all.
        case excluded
        /// No plain text to share (an image, files…).
        case noText
    }

    public static func decide(types: [String]) -> Decision {
        if types.contains(where: excludedTypes.contains) {
            return .excluded
        }
        return types.contains(plainText) ? .readText : .noText
    }
}
