@Suite struct DeviceNameTests {
    @Test func keepsAValidNameWithoutItsSurroundingSpaces() throws {
        #expect(try DeviceName.check("  MacBook Air ").get() == "MacBook Air")
        #expect(try DeviceName.check("Atelier de test").get() == "Atelier de test")
    }

    @Test func refusesAnEmptyName() {
        #expect(DeviceName.check("") == .failure(.empty))
        #expect(DeviceName.check("   \n") == .failure(.empty))
    }

    @Test func refusesControlCharacters() {
        #expect(DeviceName.check("a\tb") == .failure(.controlCharacters))
        #expect(DeviceName.check("a\u{7f}b") == .failure(.controlCharacters))
        #expect(DeviceName.check("a\u{85}b") == .failure(.controlCharacters))
    }

    @Test func countsBytesNotCharacters() {
        #expect(DeviceName.check(String(repeating: "a", count: 64)).isSuccess)
        #expect(DeviceName.check(String(repeating: "a", count: 65)) == .failure(.tooLong))
        // "é" takes two bytes: 32 fit, 33 do not.
        #expect(DeviceName.check(String(repeating: "é", count: 32)).isSuccess)
        #expect(DeviceName.check(String(repeating: "é", count: 33)) == .failure(.tooLong))
        // Emoji take four.
        #expect(DeviceName.check(String(repeating: "🧵", count: 16)).isSuccess)
        #expect(DeviceName.check(String(repeating: "🧵", count: 17)) == .failure(.tooLong))
    }
}

@Suite struct PasteboardPolicyTests {
    @Test func readsPlainText() {
        #expect(PasteboardPolicy.decide(types: ["public.utf8-plain-text"]) == .readText)
        #expect(PasteboardPolicy.decide(types: ["public.html", "public.utf8-plain-text"]) == .readText)
    }

    @Test func leavesMarkedContentAlone() {
        for marker in [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
        ] {
            #expect(PasteboardPolicy.decide(types: ["public.utf8-plain-text", marker]) == .excluded)
            #expect(PasteboardPolicy.decide(types: [marker]) == .excluded)
        }
    }

    @Test func theSourceMarkerAloneExcludesNothing() {
        let types = ["public.utf8-plain-text", "org.nspasteboard.source"]
        #expect(PasteboardPolicy.decide(types: types) == .readText)
    }

    @Test func ignoresContentWithoutText() {
        #expect(PasteboardPolicy.decide(types: ["public.png"]) == .noText)
        #expect(PasteboardPolicy.decide(types: ["public.file-url"]) == .noText)
        #expect(PasteboardPolicy.decide(types: []) == .noText)
    }
}

@Suite struct QRCodeTests {
    /// About as long as a real pairing code on the public relay.
    let code = "WEFT1:F3dzczovL3dlZnQuZnJvaHViLmV1L3YxAAECAwQFBgcICQoLDA0ODxAREhMUFRYXGBkaGxwdHh8gISIjJCUmJygpKissLS4vMDEyMzQ1Njc4OTo7PD0-P0BBQkNERUZHSElKS0xNTk9QUVJTVFVWV1hZWltcXV5fYGFiYw"

    func decode(_ image: CGImage) -> [String] {
        let detector = CIDetector(
            ofType: CIDetectorTypeQRCode,
            context: nil,
            options: [CIDetectorAccuracy: CIDetectorAccuracyHigh]
        )
        let features = detector?.features(in: CIImage(cgImage: image)) ?? []
        return features.compactMap { ($0 as? CIQRCodeFeature)?.messageString }
    }

    @Test func producesADecodableImage() throws {
        let qr = try #require(QRCode(code))
        let image = try #require(qr.image(scale: 8))
        #expect(decode(image) == [code])
    }

    @Test func drawsWholePixelsWithAQuietZone() throws {
        let qr = try #require(QRCode(code))
        // A version that holds the code: 21 + 4 × version modules.
        #expect(qr.size >= 21 && (qr.size - 21) % 4 == 0)
        let image = try #require(qr.image(scale: 6))
        #expect(image.width == (qr.size + 8) * 6)
        #expect(image.height == image.width)

        // The red channel of each pixel, from the top-left corner.
        let data = try #require(image.dataProvider?.data as Data?)
        func red(_ x: Int, _ y: Int) -> UInt8 {
            data[y * image.bytesPerRow + x * image.bitsPerPixel / 8]
        }
        func isWhite(_ x: Int, _ y: Int) -> Bool { red(x, y) == 255 }
        func isBlack(_ x: Int, _ y: Int) -> Bool { red(x, y) == 0 }
        // The quiet zone is white all around…
        for offset in stride(from: 0, to: image.width, by: 5) {
            #expect(isWhite(offset, 0) && isWhite(0, offset))
            #expect(isWhite(offset, 4 * 6 - 1) && isWhite(4 * 6 - 1, offset))
        }
        // …and the top-left finder pattern starts right after it, with no
        // grey edge.
        #expect(isBlack(4 * 6, 4 * 6))
        #expect(isBlack(4 * 6 + 5, 4 * 6 + 5))
        for x in 0..<image.width {
            #expect(isWhite(x, 4 * 6 + 3) || isBlack(x, 4 * 6 + 3))
        }
    }

    @Test func decodesAShortCodeAtASmallScale() throws {
        let qr = try #require(QRCode("WEFT1:short"))
        let image = try #require(qr.image(scale: 4))
        #expect(decode(image) == ["WEFT1:short"])
    }
}

@Suite struct WordsTests {
    @Test func countsDown() {
        #expect(Words.countdown(secondsLeft: 300) == "5:00")
        #expect(Words.countdown(secondsLeft: 65) == "1:05")
        #expect(Words.countdown(secondsLeft: -3) == "0:00")
    }

    @Test func showsTheRelayHost() {
        #expect(Words.relayHost("wss://weft.frohub.eu/v1") == "weft.frohub.eu")
        #expect(Words.relayHost("ws://127.0.0.1:8095/v1") == "127.0.0.1:8095")
    }

    @Test func namesPlatforms() {
        #expect(Words.platform("android") == "Android")
        #expect(Words.platform(nil) == nil)
        #expect(Words.symbol("windows") == "pc")
        #expect(Words.symbol(nil) == "laptopcomputer.and.iphone")
    }

    @Test func writesBatteryLevelsPerLanguage() {
        #expect(Words.battery(level: 87, language: .english) == "87%")
        #expect(Words.battery(level: 87, language: .french) == "87\u{a0}%")
    }

    @Test func picksTheLanguage() {
        #expect(Language.detect(forced: "fr", preferred: ["en-US"]) == .french)
        #expect(Language.detect(forced: nil, preferred: ["fr-FR", "en"]) == .french)
        #expect(Language.detect(forced: nil, preferred: ["de-DE", "en-GB"]) == .english)
        #expect(Language.detect(forced: nil, preferred: ["ja"]) == .english)
    }
}

