@Suite struct DeviceNameTests {
    @Test func keepsAValidNameWithoutItsSurroundingSpaces() throws {
        #expect(try DeviceName.check("  MacBook Air ").get() == "MacBook Air")
        #expect(try DeviceName.check("Atelier de test").get() == "Atelier de test")
    }

    @Test func refusesAnEmptyName() {
        #expect(DeviceName.check("") == .failure(.empty))
        #expect(DeviceName.check("   \n") == .failure(.empty))
    }

    @Test func refusesControlCharacters() {
        #expect(DeviceName.check("a\tb") == .failure(.controlCharacters))
        #expect(DeviceName.check("a\u{7f}b") == .failure(.controlCharacters))
        #expect(DeviceName.check("a\u{85}b") == .failure(.controlCharacters))
    }

    @Test func countsBytesNotCharacters() {
        #expect(DeviceName.check(String(repeating: "a", count: 64)).isSuccess)
        #expect(DeviceName.check(String(repeating: "a", count: 65)) == .failure(.tooLong))
        // "é" takes two bytes: 32 fit, 33 do not.
        #expect(DeviceName.check(String(repeating: "é", count: 32)).isSuccess)
        #expect(DeviceName.check(String(repeating: "é", count: 33)) == .failure(.tooLong))
        // Emoji take four.
        #expect(DeviceName.check(String(repeating: "🧵", count: 16)).isSuccess)
        #expect(DeviceName.check(String(repeating: "🧵", count: 17)) == .failure(.tooLong))
    }
}

